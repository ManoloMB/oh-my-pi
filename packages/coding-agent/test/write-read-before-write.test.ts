import { afterEach, beforeAll, beforeEach, describe, expect, it } from "bun:test";
import * as fs from "node:fs/promises";
import * as os from "node:os";
import * as path from "node:path";
import { Settings } from "@oh-my-pi/pi-coding-agent/config/settings";
import type { ToolSession } from "@oh-my-pi/pi-coding-agent/tools";
import { ReadTool } from "@oh-my-pi/pi-coding-agent/tools/read";
import { WriteTool } from "@oh-my-pi/pi-coding-agent/tools/write";

function createSession(cwd: string, enforce = true): ToolSession {
	return {
		cwd,
		hasUI: false,
		getSessionFile: () => path.join(cwd, "session.jsonl"),
		getSessionSpawns: () => "*",
		getArtifactsDir: () => path.join(cwd, "artifacts"),
		allocateOutputArtifact: async () => ({ id: "artifact-1", path: path.join(cwd, "artifact-1.log") }),
		settings: Settings.isolated({
			"edit.blockAutoGenerated": false,
			"edit.mode": "replace",
			"edit.enforceReadBeforeWrite": enforce,
		}),
		enableLsp: false,
	};
}

describe("write tool read-before-overwrite gate", () => {
	let tmpDir: string;

	beforeAll(async () => {
		await Settings.init({ inMemory: true });
	});

	beforeEach(async () => {
		tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), "write-read-before-write-test-"));
	});

	afterEach(async () => {
		await fs.rm(tmpDir, { recursive: true, force: true });
	});

	it("refuses to overwrite an existing file this session has not read", async () => {
		const filePath = path.join(tmpDir, "unread.txt");
		await Bun.write(filePath, "original\n");

		await expect(
			new WriteTool(createSession(tmpDir)).execute("write-1", { path: filePath, content: "replaced\n" }),
		).rejects.toThrow("has not read it");
		expect(await Bun.file(filePath).text()).toBe("original\n");
	});

	it("allows the overwrite after the file was read", async () => {
		const filePath = path.join(tmpDir, "read.txt");
		await Bun.write(filePath, "original\n");
		const session = createSession(tmpDir);

		await new ReadTool(session).execute("read-1", { path: filePath });
		await new WriteTool(session).execute("write-1", { path: filePath, content: "replaced\n" });

		expect(await Bun.file(filePath).text()).toBe("replaced\n");
	});

	it("refuses when the file changed on disk after the read", async () => {
		const filePath = path.join(tmpDir, "changed.txt");
		await Bun.write(filePath, "original\n");
		const session = createSession(tmpDir);

		await new ReadTool(session).execute("read-1", { path: filePath });
		await Bun.write(filePath, "changed externally\n");

		await expect(
			new WriteTool(session).execute("write-1", { path: filePath, content: "replaced\n" }),
		).rejects.toThrow("changed on disk");
		expect(await Bun.file(filePath).text()).toBe("changed externally\n");
	});

	it("creates a new file without a prior read", async () => {
		const filePath = path.join(tmpDir, "new.txt");

		await new WriteTool(createSession(tmpDir)).execute("write-1", { path: filePath, content: "fresh\n" });

		expect(await Bun.file(filePath).text()).toBe("fresh\n");
	});

	it("overwrites unread files when edit.enforceReadBeforeWrite is off", async () => {
		const filePath = path.join(tmpDir, "opt-out.txt");
		await Bun.write(filePath, "original\n");

		await new WriteTool(createSession(tmpDir, false)).execute("write-1", { path: filePath, content: "replaced\n" });

		expect(await Bun.file(filePath).text()).toBe("replaced\n");
	});

	it("allows a second write right after a successful write", async () => {
		const filePath = path.join(tmpDir, "rewrite.txt");
		const session = createSession(tmpDir);
		const write = new WriteTool(session);

		await write.execute("write-1", { path: filePath, content: "first\n" });
		await write.execute("write-2", { path: filePath, content: "second\n" });

		expect(await Bun.file(filePath).text()).toBe("second\n");
	});
});
